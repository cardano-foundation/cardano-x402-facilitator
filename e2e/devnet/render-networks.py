"""Renders the facilitator NETWORKS_FILE for the running devnet.

The devnet's genesis start time changes on every run, so the slot-config must be
read from the live DevKit admin API — after the devnet is up and before the
facilitators start.

Usage: python3 -I render-networks.py <admin-base-url> <masumi-deployment.json> <out-file>
"""

import json
import sys
import urllib.request

admin, masumi_file, out_file = sys.argv[1].rstrip("/"), sys.argv[2], sys.argv[3]

with urllib.request.urlopen(admin + "/local-cluster/api/admin/devnet", timeout=10) as response:
    devnet = json.load(response)
if devnet.get("protocolMagic") != 2:
    sys.exit(f"devnet protocolMagic is {devnet.get('protocolMagic')}, expected 2 (cardano:preview)")

with open(masumi_file) as f:
    masumi_hash = json.load(f)["allowlisted"]["scriptHash"]

slot_length_ms = round(float(devnet["slotLength"]) * 1000)
config = f"""# Generated by e2e/devnet/render-networks.py — do not edit.
x402:
  networks:
    - id: cardano:preview
      chain:
        blockfrost:
          base-url: http://shim:16061/api/v1/
          project-id: devnet
      slot-config:
        zero-slot: 0
        zero-time-epoch-seconds: {int(devnet["startTime"])}
        slot-length-ms: {slot_length_ms}
  masumi:
    allowed-script-hashes:
      "[cardano:preview]":
        - {masumi_hash}
"""
with open(out_file, "w") as f:
    f.write(config)
print(f"rendered {out_file}: startTime={devnet['startTime']} slotLength={slot_length_ms}ms masumi={masumi_hash}")
